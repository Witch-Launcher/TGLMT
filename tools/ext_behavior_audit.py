#!/usr/bin/env python3
"""Static behavior audit for advertised OpenGL extensions.

Flags advertised extensions whose entry points exist but whose bodies are
no-ops (empty or only `(void)arg;` / `return;`). This is deliberately
conservative: a non-empty body can still be wrong, but an empty body is proof.

Usage:
  python3 tools/ext_behavior_audit.py
  python3 tools/ext_behavior_audit.py --write
"""
import argparse
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import ext_matrix as matrix

SRC = ROOT / "src/gl"
DOC = ROOT / "docs/EXTENSION_BEHAVIOR_AUDIT.md"
JSON = ROOT / "docs/ext_behavior_audit.json"

DEF_RE = re.compile(
    r"(?m)^[\w:<>\*&\s,]+?\b(gl[A-Za-z0-9_]+)\s*\([^;{}]*\)\s*\{([^{}]*)\}"
)
ALIAS_RE = re.compile(
    r"void\s+(gl[A-Za-z0-9_]+)\s*\([^)]*\)\s*\{\s*tglmt::gl::(gl[A-Za-z0-9_]+)\s*\("
)
KNOWN_BAD = {
    "GL_ARB_gl_spirv":
        "glSpecializeShader recompiles GLSL; glShaderBinary is a no-op",
    "GL_EXT_provoking_vertex":
        "glProvokingVertex only stores shadow state; the draw path ignores it",
    "GL_OES_texture_storage_multisample_2d_array":
        "glTexStorage3DMultisampleOES forwards to a no-op core function",
}
ALLOW_NOOP = {
    # A bounding box is explicitly a hint; ignoring it is spec-valid.
    "glPrimitiveBoundingBox",
    "glPrimitiveBoundingBoxARB",
}


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    return text


def body_kind(body):
    body = re.sub(r"\(void\)\s*[A-Za-z_][A-Za-z0-9_]*\s*;", "", body)
    body = re.sub(r"\breturn\s*;", "", body)
    body = body.strip()
    if body == "":
        return "noop"
    if re.fullmatch(r"return\s+(?:-?\d+|GL_[A-Z0-9_]+|true|false)\s*;", body):
        return "constant"
    return None


def definitions():
    found = {}
    for path in sorted(SRC.glob("*.cpp")):
        if path.name in ("gl_stubs_gen.cpp", "gl_ext_aliases_gen.cpp",
                         "gl_c_exports.cpp", "gl_dispatch_gen.cpp"):
            continue
        text = strip_comments(path.read_text())
        for match in DEF_RE.finditer(text):
            name, body = match.group(1), match.group(2)
            kind = body_kind(body)
            if kind and name not in ALLOW_NOOP:
                found.setdefault(name, {"file": str(path.relative_to(ROOT)),
                                        "kind": kind})
    return found


def aliases():
    path = SRC / "gl_ext_aliases_gen.cpp"
    if not path.exists():
        return {}
    text = strip_comments(path.read_text())
    return {m.group(1): m.group(2) for m in ALIAS_RE.finditer(text)}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()

    core, exts = matrix.parse_registry()
    kexts = matrix.read_kexts()
    noops = definitions()
    alias_map = aliases()
    rows = []
    for name in sorted(set(kexts)):
        info = exts.get(name)
        if not info:
            continue
        hits = []
        for fn in sorted(info["funcs"]):
            if fn in noops:
                hits.append({"function": fn, **noops[fn]})
            elif fn in alias_map and alias_map[fn] in noops:
                hits.append({"function": fn, **noops[alias_map[fn]],
                             "via": alias_map[fn]})
        if name in KNOWN_BAD or hits:
            rows.append({"name": name, "reason": KNOWN_BAD.get(name, ""),
                         "noops": hits})

    print(f"advertised extensions: {len(set(kexts))}")
    print(f"extensions with no-op entry points: {len(rows)}")
    for row in rows:
        print(f"  {row['name']}: {len(row['noops'])}")
        if row["reason"]:
            print(f"    reason: {row['reason']}")
        for item in row["noops"][:8]:
            via = f" -> {item['via']}" if item.get("via") else ""
            print(f"    {item['function']:48}{via}  {item['kind']}  {item['file']}")
        if len(row["noops"]) > 8:
            print(f"    ... {len(row['noops']) - 8} more")

    if args.write:
        lines = [
            "# Advertised extension behavior audit",
            "",
            "Generated by `python3 tools/ext_behavior_audit.py --write`.",
            "A no-op entry point is proof that the advertised extension is not truthful.",
            "",
            f"- Advertised extensions: **{len(set(kexts))}**",
            f"- Advertised extensions with no-op entry points: **{len(rows)}**",
            "",
            "| Extension | Reason | No-op functions | Files |",
            "|---|---|---|---|",
        ]
        for row in rows:
            funcs = ", ".join(
                f"`{x['function']}`" + (f" -> `{x['via']}`" if x.get("via") else "")
                + f" ({x['kind']})"
                for x in row["noops"])
            files = ", ".join(sorted({x["file"] for x in row["noops"]}))
            reason = row["reason"].replace("|", "\\|")
            lines.append(f"| `{row['name']}` | {reason} | {funcs} | {files} |")
        DOC.write_text("\n".join(lines) + "\n")
        JSON.write_text(json.dumps({
            "advertised_extensions": len(set(kexts)),
            "rows": rows,
        }, indent=2) + "\n")
        print(f"wrote {DOC.relative_to(ROOT)}, {JSON.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
